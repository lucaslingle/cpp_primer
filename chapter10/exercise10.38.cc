/*
List the five iterator categories and the operations that each supports.
*/

// input iterator:
// supports equality and inequality
// prefix and postfix increment
// dereference for read, and arrow for methods

// output iterator:
// supports prefix and postfix increment
// dereference for assignment only

// forward iterator:
// supports equality and inequality
// prefix and postfix increment
// dereference for read and write, and arrow for methods

// bidirectional iterator:
// supports equality and inequality
// prefix and postfix increment
// prefix and postfix decrement
// dereference for read and write, and arrow for methods

// random access iterator:
// supports equality, inequality, and relational operators
// prefix and postfix increment
// prefix and postfix decrement
// supports addition and subtraction of iterator and int
// supports subtraction of two iterators
// dereference for read and write, and arrow for methods
// supports subscript as synonym for integer increment and dereference
