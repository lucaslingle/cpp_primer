/*
What is a function template? What is a class template?
*/

// In C++, a function template is blueprint for the compiler to generate functions.
// It leaves unspecified one or more specific types, or one or more
// specific values of a given type. When specified, these parameters cause the compiler
// to instantiate the templates (and write code) at compile time. 

// In C++, a class template is a blueprint for the compiler to generate classes.
// It leaves unspecified one or more specific types, or one or more
// specific values of a given type. When specified, these parameters cause the compiler
// to instantiate the templates (and write code) at compile time. 