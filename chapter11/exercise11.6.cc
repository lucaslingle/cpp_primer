/*
Explain the difference between a set and a list.
When might you use one or the other?
*/

// a set stores keys in order of key, with no duplicates. (multisets are different.)
// a set is useful for representing membership 
// or unary predicate status of a finite number of items. 

// a list stores items in order of position, with possible duplicates.
// a list is useful for storing items in user-defined order,
// and allowing inserts and deletes to be applied at specific positions,
// regardless of the content of the inserted or deleted item. 
