/*
Give an example of when each of list, vector, deque, map and set
might be most useful.
*/

// list: when fast inserts and deletes are needed anywhere in the list. 
//       example: a list of book titles, sold by a bookstore.
//
// vector: when fast inserts are needed at one end, and random access.
//         example: a vector of purchases, appended to in the order they occurred.
//
// deque: when fast inserts are needed at both ends, and random access.
//        example: a queue of orders to be sent out, ordered by priority. 
//
// map: when linking multiple types of data.
//      example: a mapping between isbn and book metadata.
//
// set: when specifying a deduplicated data to be used somewhere.
//      example: a set specifying customers with bounced checks.
