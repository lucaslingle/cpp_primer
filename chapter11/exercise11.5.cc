/*
Explain the difference between a map and a set. 
When might you use one or the other?
*/

// a map is an associative container that links keys to values,
// allowing additional information to be obtained when starting with a given key.
// it is useful for tasks where part of the information is available, 
// and other related information is desired.

// a set is an associative container that stores keys,
// allowing the user to query whether a given key is in the set.
// it is useful for tasks when a key is already available 
// and only the set membership is in question. 
