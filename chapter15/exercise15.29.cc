// The discrepancy is because this version uses a pointer (as it happens, shared_ptr),
// which along with references are the two types that support polymorphism in C++.
// As a result, the Bulk_quote object is not sliced down when added to the vector,
// and remains intact, with the net_price method being overridden. 

#include <iostream>
#include <string>
#include <cstddef>
#include <vector>
#include <memory>

class Quote {
    public:
        Quote() = default;
        Quote(const std::string &book, double sales_price):
            bookNo(book), price(sales_price) { }
        std::string isbn() const { return bookNo; }
        virtual double net_price(std::size_t n) const { return n * price; }
        virtual ~Quote() = default;
    private:
        std::string bookNo;
    protected:
        double price = 0.0;
};

