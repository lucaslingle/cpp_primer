class Disc_quote : public Quote {
public:
    Disc_quote() = default;
    Disc_quote(const std::string& book, double price, std::size_t qty, double disc):
        Quote(book, price), quantity(qty), discount(disc) { }
    double net_price(std::size_t) const = 0;
protected:
    std::size_t quantity = 0;
    double discount = 0.0;
};

class Bulk_quote : public Disc_quote {
public:
    using Disc_quote::Disc_quote;
    // Bulk_quote() = default;
    // Bulk_quote(const std::string& book, double price, std::size_t qty, double disc):
    //     Disc_quote(book, price, qty, disc) { }
    double net_price(std::size_t n) const override {
        if (n >= quantity)
            return (1 - discount) * n * price;
        else
            return n * price;
    }
};

int main() {
    // will NOT get sliced down, and base class net_price will NOT used.
    std::vector<std::shared_ptr<Quote>> qvec;
    qvec.push_back(
        std::make_shared<Bulk_quote>("The C++ Primer (Fifth Edition)", 69.99, 10, 0.25)
    );
    for (const auto &item : qvec)
        std::cout << item->net_price(11) << std::endl;

    return 0;
}